export type AptConActivo = {
  id_apt: number;
  id_grupo: number | null;
  nombre: string;
  activo: boolean;
};

// resolveConcreteLocations needs `activo` to expand "apartamentos activos"
// aplicaciones correctly — the shared useApartamentosLite() (used elsewhere
// for display/filtering only) doesn't select it, so this feature gets its
// own lite query rather than widening that one's shape for everyone else.
export function useApartamentosConActivoLite() {
  return useQuery({
    queryKey: ["preventivo-apts-activo"],
    queryFn: async (): Promise<AptConActivo[]> => {
      const { data, error } = await supabase
        .from("apartamentos")
        .select("id_apt,nombre,id_grupo,activo");
      if (error) throw error;
      return (data ?? []) as AptConActivo[];
    },
  });
}

